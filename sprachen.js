  // --- Funktionen -----------------------------------------------------------------------------------

  function sprache(code) {
    return SPRACHEN.find((s) => s.code === code) || SPRACHEN[0];
  }

  // Wie Hourbridge: gespeicherte Wahl, sonst die erste unterstützte aus navigator.languages (nur der Sprachteil,
  // „fr-CA“ wird „fr“), sonst Englisch
  function erkenne(gespeichert, liste) {
    if (gespeichert && CODES.has(gespeichert)) return gespeichert;
    const kandidaten = (liste || []).map((x) => String(x).toLowerCase().split("-")[0]);
    return kandidaten.find((x) => CODES.has(x)) || "en";
  }

  const formate = new Map();
  function format(code, art, optionen) {
    const schl = code + "|" + art;
    let f = formate.get(schl);
    if (!f) {
      f = new Intl.NumberFormat(sprache(code).locale, optionen);
      formate.set(schl, f);
    }
    return f;
  }
  // Ganze Zahl mit Tausendertrennung je Sprache
  function zahl(code, n) { return format(code, "zahl", { maximumFractionDigits: 0 }).format(Math.round(Number(n) || 0)); }
  // Zahl mit festen Nachkommastellen (de 3,25, en 3.25)
  function dezimal(code, n, stellen) { return format(code, "d" + stellen, { minimumFractionDigits: stellen, maximumFractionDigits: stellen, useGrouping: false }).format(Number(n) || 0); }
  // Dezimalzeichen der Sprache
  function komma(code) {
    const teil = format(code, "d1", { minimumFractionDigits: 1, maximumFractionDigits: 1, useGrouping: false }).formatToParts(1.5).find((t) => t.type === "decimal");
    return teil ? teil.value : ".";
  }
  /*
   * Rundenzeit m:ss mit stellen Nachkommastellen im Dezimalzeichen der Sprache (de 1:23,45, en 1:23.45).
   * abrunden: laufende Uhr (zeigt nie eine Zehntel, die noch nicht vergangen ist), sonst gerundet.
   * Ohne Zeit (null) steht ein Platzhalter gleicher Länge da (-:--,--).
   */
  function zeit(code, t, stellen, abrunden) {
    const k = komma(code);
    if (t == null || !isFinite(t)) return "-:--" + k + "-".repeat(stellen);
    const f = Math.pow(10, stellen);
    const ganz = abrunden ? Math.floor(Math.max(0, t) * f) : Math.round(Math.max(0, t) * f);
    const sek = Math.floor(ganz / f);
    const rest = String(ganz % f).padStart(stellen, "0");
    return Math.floor(sek / 60) + ":" + String(sek % 60).padStart(2, "0") + k + rest;
  }

  // Text zu einem Schlüssel, Platzhalter gefüllt (Zahlen je Sprache formatiert). Fehlt ein Text, steht Englisch da,
  // fehlt auch der, der Schlüssel selbst (fällt beim Prüfen auf).
  function text(code, schluessel, werte) {
    let t = (TEXTE[code] || {})[schluessel];
    if (t === undefined) t = TEXTE.en[schluessel];
    if (t === undefined) return schluessel;
    if (!werte) return t;
    return t.replace(/\{(\w+)\}/g, (ganz, name) => {
      const v = werte[name];
      if (v === undefined || v === null) return ganz;
      return typeof v === "number" ? zahl(code, v) : String(v);
    });
  }

  return { SPRACHEN, TEXTE, SCHLUESSEL_SPEICHER, sprache, erkenne, zahl, dezimal, komma, zeit, text };
